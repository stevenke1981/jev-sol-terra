#!/usr/bin/env node
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { loadConfig } from '../src/config.js';
import { createProxy } from '../src/proxy.js';
import { formatDecision, readDecisions, usageTokens } from '../src/log.js';
import { VERSION, BUILD, compareBuild } from '../src/version.js';

const HELP = `jev-effort — mid-task reasoning-effort router for Codex and Chat Completions clients

Usage:
  jev-effort serve              Run the proxy in the foreground (shows live decisions)
                                (opencode/aider/crush: base URL http://127.0.0.1:8787/v1)
  jev-effort install [--force]  Write the "jev" Codex profile ($CODEX_HOME/jev.config.toml)
  jev-effort codex [args...]    Start the proxy if needed, then run: codex -p jev [args...]
  jev-effort tail               Follow routing decisions as they happen
  jev-effort stats              Summarize past decisions and reasoning tokens per effort
  jev-effort status             Show the running proxy's version and whether it is stale
  jev-effort stop               Stop the running proxy (also one started in the background)
  jev-effort --version          Print the version and build of the code on disk

Environment:
  JEV_PORT (8787)  JEV_LEVELS (low,medium,high)  JEV_MODE (heuristic|llm|off)
  JEV_JUDGE_MODEL  JEV_UPSTREAM  JEV_HOME (~/.jev)  JEV_QUIET=1`;

const PROFILE_MARKER = '# Generated by `jev-effort install`';

function profileToml(config) {
  return `${PROFILE_MARKER}. Use with: codex -p jev
model_provider = "jev"

[model_providers.jev]
name = "Jev"
base_url = "http://${config.host}:${config.port}/v1"
wire_api = "responses"
requires_openai_auth = true
`;
}

function install(config, force) {
  const codexHome = process.env.CODEX_HOME || path.join(os.homedir(), '.codex');
  const file = path.join(codexHome, 'jev.config.toml');
  if (fs.existsSync(file) && !force && !fs.readFileSync(file, 'utf8').startsWith(PROFILE_MARKER)) {
    throw new Error(`${file} exists and was not written by jev; rerun with --force to overwrite`);
  }
  fs.mkdirSync(codexHome, { recursive: true });
  fs.writeFileSync(file, profileToml(config));
  console.log(`wrote ${file}\nrun: jev-effort codex   (or start "jev-effort serve" and use: codex -p jev)`);
}

/** @returns {Promise<object|null>} the running proxy's /jev/health payload, or null */
async function probe(config) {
  try {
    const res = await fetch(`http://${config.host}:${config.port}/jev/health`, { signal: AbortSignal.timeout(500) });
    return res.ok ? await res.json() : null;
  } catch {
    return null;
  }
}

async function healthy(config) {
  return (await probe(config)) != null;
}

async function ensureProxy(config) {
  const running = await probe(config);
  if (running) {
    const check = compareBuild(running);
    if (check.status === 'stale') console.error(`jev: warning: ${check.message}`);
    return;
  }
  fs.mkdirSync(config.home, { recursive: true });
  const out = fs.openSync(path.join(config.home, 'proxy.log'), 'a');
  const self = fileURLToPath(import.meta.url);
  spawn(process.execPath, [self, 'serve'], { detached: true, stdio: ['ignore', out, out], windowsHide: true }).unref();
  for (let i = 0; i < 30; i++) {
    await new Promise((r) => setTimeout(r, 100));
    if (await healthy(config)) return;
  }
  throw new Error(`proxy did not start; see ${path.join(config.home, 'proxy.log')}`);
}

// On Windows `codex` is a .cmd shim; running it through cmd.exe would re-parse the
// user's arguments (`&`, `%VAR%`). Launch the npm package's JS entry with node instead.
function codexCommand() {
  if (process.platform !== 'win32') return { file: 'codex', prefix: [] };
  const dirs = (process.env.PATH ?? '').split(path.delimiter).filter(Boolean);
  if (process.env.APPDATA) dirs.push(path.join(process.env.APPDATA, 'npm'));
  for (const dir of dirs) {
    const entry = path.join(dir, 'node_modules', '@openai', 'codex', 'bin', 'codex.js');
    if (fs.existsSync(path.join(dir, 'codex.cmd')) && fs.existsSync(entry)) {
      return { file: process.execPath, prefix: [entry] };
    }
  }
  throw new Error('cannot find the npm-installed Codex (codex.cmd + @openai/codex); start "jev-effort serve" and run: codex -p jev');
}

async function runCodex(config, args) {
  await ensureProxy(config);
  const { file, prefix } = codexCommand();
  const child = spawn(file, [...prefix, '-p', 'jev', ...args], { stdio: 'inherit' });
  child.on('error', (err) => {
    console.error(`jev: cannot start codex: ${err.message}`);
    process.exit(1);
  });
  child.on('exit', (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
}

function serve(config) {
  const { server } = createProxy(config);
  server.on('error', async (err) => {
    let hint = '';
    if (err.code === 'EADDRINUSE') {
      const running = await probe(config);
      hint = running
        ? `; a jev proxy is already there: ${compareBuild(running).message}`
        : ` (port ${config.port} in use by something else; set JEV_PORT)`;
    }
    console.error(`jev: ${err.message}${hint}`);
    process.exit(1);
  });
  server.listen(config.port, config.host, () => {
    console.log(`jev v${VERSION} (build ${BUILD}) listening on http://${config.host}:${config.port}/v1  `
      + `mode=${config.mode}  ladder=${config.ladder.join('→')}`);
  });
}

async function status(config) {
  const running = await probe(config);
  if (!running) {
    console.log(`no jev proxy on http://${config.host}:${config.port} (code on disk: v${VERSION} build ${BUILD})`);
    process.exitCode = 1;
    return;
  }
  const check = compareBuild(running);
  console.log(`${check.message}  mode=${running.mode}`);
  if (check.status === 'stale') process.exitCode = 1;
}

const STOP_WAIT_MS = 3000;

// Stops whichever jev proxy holds the port, including one started in the
// background by `jev-effort codex`. The PID comes from /jev/health, so only a
// process that answers as jev is ever signalled.
async function stop(config) {
  const running = await probe(config);
  if (!running) {
    console.log(`no jev proxy on http://${config.host}:${config.port}`);
    return;
  }
  if (!Number.isInteger(running.pid)) {
    console.error(`jev: the proxy on port ${config.port} predates "jev-effort stop" and does not report its PID; stop it with:\n`
      + `  PowerShell: Stop-Process -Id (Get-NetTCPConnection -LocalPort ${config.port} -State Listen).OwningProcess\n`
      + `  macOS/Linux: kill $(lsof -t -iTCP:${config.port} -sTCP:LISTEN)`);
    process.exitCode = 1;
    return;
  }
  try {
    process.kill(running.pid);
  } catch (err) {
    if (err.code !== 'ESRCH') throw new Error(`cannot stop pid ${running.pid}: ${err.message}`);
  }
  for (let waited = 0; waited < STOP_WAIT_MS; waited += 100) {
    if (!(await healthy(config))) {
      console.log(`stopped jev proxy (pid ${running.pid}, v${running.version} build ${running.build})`);
      return;
    }
    await new Promise((r) => setTimeout(r, 100));
  }
  console.error(`jev: pid ${running.pid} is still answering on port ${config.port} after ${STOP_WAIT_MS} ms`);
  process.exitCode = 1;
}

function tail(config) {
  let size = fs.existsSync(config.logFile) ? fs.statSync(config.logFile).size : 0;
  console.log(`following ${config.logFile} (Ctrl+C to stop)`);
  fs.mkdirSync(path.dirname(config.logFile), { recursive: true });
  fs.watchFile(config.logFile, { interval: 300 }, (cur) => {
    if (cur.size <= size) {
      size = cur.size;
      return;
    }
    const fd = fs.openSync(config.logFile, 'r');
    const buf = Buffer.alloc(cur.size - size);
    fs.readSync(fd, buf, 0, buf.length, size);
    fs.closeSync(fd);
    size = cur.size;
    for (const line of buf.toString('utf8').split('\n').filter(Boolean)) {
      try {
        console.log(formatDecision(JSON.parse(line)));
      } catch {
        // Skip a partially written line.
      }
    }
  });
}

function stats(config) {
  const rows = readDecisions(config.logFile);
  if (rows.length === 0) return console.log(`no decisions yet in ${config.logFile}`);
  const by = {};
  for (const r of rows) {
    const s = (by[r.effort] ??= { gens: 0, reasoning: 0, output: 0 });
    s.gens++;
    const t = usageTokens(r.usage);
    s.reasoning += t.reasoning ?? 0;
    s.output += t.output ?? 0;
  }
  const jevCost = rows.reduce((sum, r) => sum + (r.cost ?? 0), 0);
  const jevCalls = rows.filter((r) => r.source === 'jev').length;
  console.log(`${rows.length} generations, ${new Set(rows.map((r) => r.session)).size} sessions, `
    + `${jevCalls} routed by Jev ($${jevCost.toFixed(6)})`);
  for (const effort of config.ladder.filter((e) => by[e])) {
    const s = by[effort];
    console.log(`  ${effort.padEnd(7)} ${String(s.gens).padStart(5)} gens  ${String(Math.round(s.reasoning / s.gens)).padStart(6)} avg reasoning tok  ${s.output} output tok`);
  }
}

async function main() {
  const [cmd, ...rest] = process.argv.slice(2);
  const config = loadConfig();
  switch (cmd) {
    case 'serve': return serve(config);
    case 'install': return install(config, rest.includes('--force'));
    case 'codex': return runCodex(config, rest);
    case 'tail': return tail(config);
    case 'stats': return stats(config);
    case 'status': return status(config);
    case 'stop': return stop(config);
    case '--version':
    case '-v': return console.log(`jev-effort v${VERSION} (build ${BUILD})`);
    default: console.log(HELP);
  }
}

main().catch((err) => {
  console.error(`jev: ${err.message}`);
  process.exit(1);
});
